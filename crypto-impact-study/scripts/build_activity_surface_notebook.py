def summary(fits: dict, cells: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for name, fit in fits.items():
        sc = fit.scales.rename(columns={'q_scale': 'fitted_q_scale', 'r_scale': 'fitted_r_scale'})
